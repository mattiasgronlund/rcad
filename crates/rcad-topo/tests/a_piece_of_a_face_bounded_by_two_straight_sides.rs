//! A block two of whose walls carry one plane, and the two-sided piece that
//! leaves in the arrangement.
//!
//! The bytes are the second half of the `two_solids_fused_by_a_stranger`
//! corpus entry `crash-7d309176caedc7140756f167d7db5e7740eff1c3`, which is the
//! half that decodes — carried here rather than described, because every
//! attempt to write the same solid down through [`SolidBuilder`] was refused
//! somewhere else along the way and stopped being the shape that found this.
//! `docs/decisions.md` §67 has the argument.
//!
//! **What the bytes are.** Two blocks, ten across, a long way apart. The second
//! one has its `x = 5` wall written down carrying the plane of its
//! `y = 5.1865234375` wall, leaned by `1.8e-304` so the two are not one plane
//! and [`Arrangement::crossing_like`]'s exact determinant keeps them as two
//! crossings; its `x = 15` wall carries the plane `x = -5`.
//!
//! **Why nothing before the fuse says so.** `Model::validate` measures a corner
//! against its own face's plane and allows `Model::allowed_wobble`, which is
//! the model's *own declared* `Scale` times `Scale::RELATIVE_LINEAR_TOLERANCE`.
//! These bytes declare a part `1.8e21` mm across, which buys `1.8e12` mm of
//! room, and the two walls are twenty and ten out. The fuse does not catch it
//! either: `bake::derive_a_corner` rederives every corner as the meet of three
//! of the surfaces around it and checks the rest pass through *that* point, so
//! a model whose planes are self-consistent and whose stored corners are
//! somewhere else bakes into a different solid without complaint.
//!
//! So the bottom face is arranged against two crossings that are two different
//! straight lines, one corner of it lies on both, and the walk comes back with
//! a cycle of two straight sides. Two straight lines enclose no area.

use rcad_predicates::{Policy, ProvenanceLog};
use rcad_topo::{Error, Invalid, Model, Rule};

#[test]
fn a_wall_wearing_its_neighbours_plane_is_refused_and_does_not_crash_the_fuse() {
    let mut model = the_model_the_fuzzer_found();
    let solids: Vec<_> = model.solids().map(|solid| solid.key()).collect();
    assert_eq!(solids.len(), 2, "the bytes carry two blocks");

    let refused = model.fuse(
        &solids,
        &[],
        Rule::Difference,
        &Policy::tolerant(model.scale().nominal_size()),
        &mut ProvenanceLog::new(),
    );

    assert!(
        matches!(
            refused,
            Err(Error::Invalid(Invalid::WireTooShort { count: 2 }))
        ),
        "a piece bounded by two straight sides is a refusal, not a crash: {refused:?}"
    );
}

/// The same fuse under [`Policy::certified`] never reaches the walk.
///
/// It gives up on the crossing of two of the leaning planes instead, which is
/// why this only ever showed up on the tolerant draw: a policy with slop
/// approximates that crossing and carries on into an arrangement built on it.
#[test]
fn a_certified_policy_gives_up_before_it_gets_that_far() {
    let mut model = the_model_the_fuzzer_found();
    let solids: Vec<_> = model.solids().map(|solid| solid.key()).collect();

    let refused = model.fuse(
        &solids,
        &[],
        Rule::Difference,
        &Policy::certified(),
        &mut ProvenanceLog::new(),
    );

    assert!(
        matches!(refused, Err(Error::Undecidable { .. })),
        "a certified fuse refuses these blocks by name: {refused:?}"
    );
}

/// The model the bytes decode to, having passed the sweep the way it did on the
/// way to the fuse.
fn the_model_the_fuzzer_found() -> Model {
    let bytes = what_the_fuzzer_wrote();
    let model: Model = postcard::from_bytes(&bytes).expect("the corpus entry decodes");
    model
        .validate(&Policy::certified(), &mut ProvenanceLog::new())
        .expect("the sweep lets these blocks through, which is how they reach the fuse");
    model
}

fn what_the_fuzzer_wrote() -> Vec<u8> {
    let digits = THE_CORPUS_ENTRYS_SECOND_HALF.as_bytes();
    assert!(digits.len().is_multiple_of(2), "hex comes in pairs");
    digits
        .chunks(2)
        .map(|pair| {
            let text = core::str::from_utf8(pair).expect("hex is ascii");
            u8::from_str_radix(text, 16).expect("hex is hex")
        })
        .collect()
}

